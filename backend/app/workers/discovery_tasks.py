async def _check_recruitee(client: httpx.AsyncClient, slug: str) -> bool:
    try:
        r = await client.get(
            f"https://{slug}.recruitee.com/api/offers/?scope=published&limit=1",
            timeout=7)
        if r.status_code != 200:
            return False
        data = r.json()
        return len(data.get("offers", [])) > 0 if isinstance(data, dict) else False
    except Exception:
        return False


# Workday WD version numbers to try (cover 95% of tenants)
_WD_VERSIONS = ("wd1", "wd2", "wd3", "wd5", "wd12")


async def _check_workday(client: httpx.AsyncClient, slug: str) -> str | None:
    """Returns 'slug.wdN' ATS identifier if a live Workday tenant is found."""
    for wd in _WD_VERSIONS:
        try:
            r = await client.get(
                f"https://{slug}.{wd}.myworkdayjobs.com",
                timeout=8,
            )
            # Valid Workday tenants return 200 with the WD JS app
            if r.status_code == 200 and "workday" in r.text.lower():
                return f"{slug}.{wd}"
        except Exception:
            pass
    return None


async def _check_teamtailor(client: httpx.AsyncClient, slug: str) -> bool:
    """TeamTailor: {slug}.teamtailor.com/jobs.json"""
    try:
        r = await client.get(
            f"https://{slug}.teamtailor.com/jobs.json", timeout=7)
        if r.status_code != 200:
            return False
        data = r.json()
        return isinstance(data, dict) and len(data.get("jobs", [])) > 0
    except Exception:
        return False


async def _check_personio(client: httpx.AsyncClient, slug: str) -> bool:
    """Personio: {slug}.jobs.personio.de/xml or .com/xml"""
    for domain in (
        f"https://{slug}.jobs.personio.de",
        f"https://{slug}.jobs.personio.com",
    ):
        try:
            r = await client.get(f"{domain}/xml", timeout=7)
            if (
                r.status_code == 200
                and len(r.text) > 300
                and ("<position" in r.text.lower() or "<jobs" in r.text.lower())
            ):
                return True
        except Exception:
            pass
    return False


async def _check_icims(client: httpx.AsyncClient, slug: str) -> bool:
    """iCIMS: {slug}.icims.com/jobs/intro"""
    try:
        r = await client.get(
            f"https://{slug}.icims.com/jobs/intro", timeout=8)
        return r.status_code in (200, 301, 302) and "icims" in r.text.lower()
    except Exception:
        return False


# ── YC company fetch ──────────────────────────────────────────────────────────

async def _fetch_yc_names(client: httpx.AsyncClient) -> list[str]:
    """Return all YC company names via their public API."""
    names: list[str] = []
    page = 1
    while True:
        try:
            r = await client.get(
                "https://api.ycombinator.com/v0.1/companies",
                params={"page": page, "per_page": 100},
                timeout=15,
            )
            if r.status_code != 200:
                break
            batch = r.json().get("companies", [])
            if not batch:
                break
            for c in batch:
                if c.get("name"):
                    names.append(c["name"])
            page += 1
            if page > 200:
                break
        except Exception as e:
            logger.warning("yc_fetch_error", error=str(e))
            break
    return names


async def _fetch_sec_edgar_names(client: httpx.AsyncClient) -> list[str]:
    """Fetch ~10,000 public US company names from SEC EDGAR company_tickers.json."""
    names: list[str] = []
    try:
        r = await client.get(
            "https://www.sec.gov/files/company_tickers.json",
            headers={"User-Agent": "JobJarvis/1.0 ramvamshikrishna0@gmail.com"},
            timeout=20,
        )
        if r.status_code == 200:
            data = r.json()
            for entry in data.values():
                title = entry.get("title", "")
                if title and len(title) > 1:
                    names.append(title.title())
    except Exception as e:
        logger.warning("sec_edgar_fetch_error", error=str(e))
    logger.info("sec_edgar_names", count=len(names))
    return names


async def _get_existing_slugs(db) -> set[str]:
    r = await db.execute(select(Company.ats_identifier))
    return {row[0] for row in r.fetchall() if row[0]}


async def _insert_company(
    db,
    name: str,
    ats_type: str,
    slug: str,
    domain: str | None = None,
    priority_score: int = 50,
    country: str = "US",
):
    stmt = pg_insert(Company).values(
        name=name,
        domain=domain,
        ats_type=ats_type,
        ats_identifier=slug,
        country=country,
        priority_score=priority_score,
        scan_frequency_minutes=720,
        next_scan_at=datetime.now(timezone.utc) + timedelta(minutes=10),
        active=True,
    ).on_conflict_do_nothing(index_elements=["name"])
    await db.execute(stmt)


# ── Main discovery ────────────────────────────────────────────────────────────

async def _discover_async(quick: bool = False) -> dict:
    sem   = asyncio.Semaphore(CONCURRENCY)
    found: list[tuple[str, str, str]] = []

    async with httpx.AsyncClient(
        headers={"User-Agent": "JobJarvis/1.0 auto-discovery"},
        follow_redirects=True,
        timeout=10,
    ) as client:

        logger.info("discovery_start", quick=quick)

        # Load CSV companies (built by scripts/build_company_list.py)
        csv_rows    = _load_csv_companies()
        # Build a lookup: name → {domain, priority_score, country}
        csv_meta: dict[str, dict] = {
            row["name"]: row for row in csv_rows
        }
        csv_names = list(csv_meta.keys())

        # Build candidate pool: CSV + YC + SEC EDGAR + hardcoded US companies
        yc_names    = await _fetch_yc_names(client)
        edgar_names = await _fetch_sec_edgar_names(client)
        all_names   = list(dict.fromkeys(
            csv_names + yc_names + edgar_names + _US_COMPANY_NAMES
        ))
        logger.info("discovery_name_pool",
                    csv=len(csv_names), yc=len(yc_names),
                    edgar=len(edgar_names), us=len(_US_COMPANY_NAMES),
                    total=len(all_names))

        # Derive slugs for GH/Lever/Ashby/SR probing
        name_slug_pairs: list[tuple[str, str]] = []
        seen: set[str] = set()
        for name in all_names:
            for slug in _derive_slugs(name)[:2]:
                if slug not in seen:
                    name_slug_pairs.append((name, slug))
                    seen.add(slug)

        # Add known Ashby slugs (exact handles, not derived)
        for slug in _ASHBY_KNOWN_SLUGS:
            if slug not in seen:
                name_slug_pairs.append((slug.replace("-", " ").title(), slug))
                seen.add(slug)

        # Known-slug lists for platform-specific probes
        workable_pairs    = [(s.replace("-", " ").title(), s) for s in _WORKABLE_KNOWN_SLUGS]
        bamboohr_pairs    = [(s.replace("-", " ").title(), s) for s in _BAMBOOHR_KNOWN_SLUGS]
        breezy_pairs      = [(s.replace("-", " ").title(), s) for s in _BREEZY_KNOWN_SLUGS]
        recruitee_pairs   = [(s.replace("-", " ").title(), s) for s in _RECRUITEE_KNOWN_SLUGS]
        workday_pairs     = [(s.replace("-", " ").title(), s) for s in _WORKDAY_KNOWN_SLUGS]
        teamtailor_pairs  = [(s.replace("-", " ").title(), s) for s in _TEAMTAILOR_KNOWN_SLUGS]
        personio_pairs    = [(s.replace("-", " ").title(), s) for s in _PERSONIO_KNOWN_SLUGS]
        icims_pairs       = [(s.replace("-", " ").title(), s) for s in _ICIMS_KNOWN_SLUGS]

        async with AsyncSessionLocal() as db:
            existing = await _get_existing_slugs(db)

        to_test        = [(n, s) for n, s in name_slug_pairs    if s not in existing]
        to_work        = [(n, s) for n, s in workable_pairs     if s not in existing]
        to_bamboo      = [(n, s) for n, s in bamboohr_pairs     if s not in existing]
        to_breezy      = [(n, s) for n, s in breezy_pairs       if s not in existing]
        to_recruitee   = [(n, s) for n, s in recruitee_pairs    if s not in existing]
        to_workday     = [(n, s) for n, s in workday_pairs      if s not in existing]
        to_teamtailor  = [(n, s) for n, s in teamtailor_pairs   if s not in existing]
        to_personio    = [(n, s) for n, s in personio_pairs      if s not in existing]
        to_icims       = [(n, s) for n, s in icims_pairs        if s not in existing]

        if quick:
            to_test       = to_test[:1000]
            to_work       = to_work[:100]
            to_bamboo     = to_bamboo[:100]
            to_breezy     = to_breezy[:100]
            to_recruitee  = to_recruitee[:100]
            to_workday    = to_workday[:50]
            to_teamtailor = to_teamtailor[:100]
            to_personio   = to_personio[:100]
            to_icims      = to_icims[:50]

        logger.info("discovery_candidates",
                    main=len(to_test), workable=len(to_work),
                    bamboohr=len(to_bamboo), breezy=len(to_breezy),
                    recruitee=len(to_recruitee), workday=len(to_workday),
                    teamtailor=len(to_teamtailor), personio=len(to_personio),
                    icims=len(to_icims), existing=len(existing))

        async def probe(name: str, slug: str):
            async with sem:
                if await _check_greenhouse(client, slug):
                    return ("greenhouse", name, slug)
                if await _check_lever(client, slug):
                    return ("lever", name, slug)
                if await _check_ashby(client, slug):
                    return ("ashby", name, slug)
                if await _check_smartrecruiters(client, slug):
                    return ("smartrecruiters", name, slug)
                return None

        async def probe_workable(name: str, slug: str):
            async with sem:
                if await _check_workable(client, slug):
                    return ("workable", name, slug)
                return None

        async def probe_bamboohr(name: str, slug: str):
            async with sem:
                if await _check_bamboohr(client, slug):
                    return ("bamboohr", name, slug)
                return None

        async def probe_breezy(name: str, slug: str):
            async with sem:
                if await _check_breezy(client, slug):
                    return ("breezy", name, slug)
                return None

        async def probe_recruitee(name: str, slug: str):
            async with sem:
                if await _check_recruitee(client, slug):
                    return ("recruitee", name, slug)
                return None

        async def probe_workday(name: str, slug: str):
            async with sem:
                identifier = await _check_workday(client, slug)
                if identifier:
                    return ("workday", name, identifier)
                return None

        async def probe_teamtailor(name: str, slug: str):
            async with sem:
                if await _check_teamtailor(client, slug):
                    return ("teamtailor", name, slug)
                return None

        async def probe_personio(name: str, slug: str):
            async with sem:
                if await _check_personio(client, slug):
                    return ("personio", name, slug)
                return None

        async def probe_icims(name: str, slug: str):
            async with sem:
                if await _check_icims(client, slug):
                    return ("icims", name, slug)
                return None

        results = await asyncio.gather(
            *[probe(n, s)            for n, s in to_test[:BATCH_LIMIT]],
            *[probe_workable(n, s)   for n, s in to_work],
            *[probe_bamboohr(n, s)   for n, s in to_bamboo],
            *[probe_breezy(n, s)     for n, s in to_breezy],
            *[probe_recruitee(n, s)  for n, s in to_recruitee],
            *[probe_workday(n, s)    for n, s in to_workday],
            *[probe_teamtailor(n, s) for n, s in to_teamtailor],
            *[probe_personio(n, s)   for n, s in to_personio],
            *[probe_icims(n, s)      for n, s in to_icims],
        )

        for r in results:
            if r:
                found.append(r)

    # Persist
    inserted = 0
    if found:
        async with AsyncSessionLocal() as db:
            for ats_type, name, slug in found:
                meta = csv_meta.get(name, {})
                await _insert_company(
                    db, name, ats_type, slug,
                    domain=meta.get("domain"),
                    priority_score=meta.get("priority_score", 50),
                    country=meta.get("country", "US"),
                )
                inserted += 1
            try:
                await db.commit()
            except Exception as e:
                logger.error("discovery_commit_error", error=str(e))
                await db.rollback()

    breakdown: dict[str, int] = {}
    for ats, _, _ in found:
        breakdown[ats] = breakdown.get(ats, 0) + 1

    total_tested = (len(to_test) + len(to_work) + len(to_bamboo)
                    + len(to_breezy) + len(to_recruitee)
                    + len(to_workday) + len(to_teamtailor)
                    + len(to_personio) + len(to_icims))
    logger.info("discovery_complete", inserted=inserted,
                breakdown=breakdown, tested=total_tested)
    return {"inserted": inserted, "breakdown": breakdown, "tested": total_tested}
