_CSV_PATH = Path("/app/data/company_list.csv")


def _load_csv_companies() -> list[dict]:
    """
    Load companies from /app/data/company_list.csv (built by build_company_list.py).
    Returns a list of dicts with keys: name, domain, industry, country,
    size_range, priority_score.  Returns [] if the file doesn't exist yet.
    """
    if not _CSV_PATH.exists():
        logger.info("company_csv_not_found", path=str(_CSV_PATH))
        return []
    rows: list[dict] = []
    try:
        with _CSV_PATH.open(newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh)
            for row in reader:
                name = (row.get("name") or "").strip()
                if name:
                    rows.append({
                        "name":           name,
                        "domain":         (row.get("domain") or "").strip() or None,
                        "industry":       (row.get("industry") or "").strip() or None,
                        "country":        (row.get("country") or "US").strip() or "US",
                        "priority_score": _safe_int(row.get("priority_score"), 50),
                    })
        logger.info("company_csv_loaded", count=len(rows), path=str(_CSV_PATH))
    except Exception as exc:
        logger.warning("company_csv_read_error", error=str(exc))
    return rows


def _safe_int(val, default: int) -> int:
    try:
        return int(val)
    except (TypeError, ValueError):
        return default


def _derive_slugs(name: str) -> list[str]:
    """Derive candidate ATS slugs from a company name."""
    n = name.lower()
    for suffix in [" inc", " corp", " ltd", " llc", " technologies",
                   " systems", " solutions", " software", " labs", " ai",
                   " tech", ", inc", ", corp", ", ltd", ".", ",",
                   " company", " group", " holdings", " brands",
                   " enterprises", " international", " global",
                   " services", " consulting", " management",
                   " partners", " associates", " agency",
                   " health", " healthcare", " financial", " capital"]:
        n = n.replace(suffix, "")
    n = n.strip()
    h = re.sub(r"[^a-z0-9]+", "-", n).strip("-")
    plain = re.sub(r"[^a-z0-9]+", "", n)
    candidates = [h, plain]
    if h.endswith("-ai"):
        candidates.append(h[:-3])
    for word in ["-technologies", "-systems", "-solutions", "-software",
                 "-health", "-healthcare", "-financial", "-capital",
                 "-analytics", "-platform", "-group"]:
        if h.endswith(word):
            candidates.append(h[: -len(word)])
    return list(dict.fromkeys(s for s in candidates if len(s) >= 2))


